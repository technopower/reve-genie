    fun addMistake(
        questionText: String,
        className: String,
        subject: String,
        chapter: String,
        topic: String,
        wrongAnswer: String,
        correctAnswer: String,
        explanation: String,
        category: String = "Concept"
    ) {
        val trimmed = questionText.trim()
        val isDuplicate = mistakeNotebook.any {
            it.question.trim().equals(trimmed, ignoreCase = true)
        }
        if (!isDuplicate) {
            val item = MistakeItem(
                id = "mistake_${System.currentTimeMillis()}_${mistakeNotebook.size + 1}",
                subject = subject,
                topic = topic,
                question = questionText,
                wrongAnswer = wrongAnswer,
                correctAnswer = correctAnswer,
                explanation = explanation,
                category = category,
                className = className,
                chapter = chapter
            )
            mistakeNotebook.add(0, item)
        }
    }

